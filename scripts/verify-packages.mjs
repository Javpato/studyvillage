import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {releaseTargets} from './release-targets.mjs';
import {verifyPackagedWeb} from './packaged-web.mjs';
const requested=process.argv[2],entry=Object.entries(releaseTargets).find(([key,target])=>key===requested||target.label===requested);
if(!entry)throw Error('Specify windows, linux, macos or android.');
const [key,target]=entry,location=key==='android'?path.resolve('deliverables/android-current/StudyVillage-development.apk'):path.resolve('deliverables',target.folder,target.app,key==='macos'?'Contents/Resources/app.asar':'resources/app.asar');
const checked=await verifyPackagedWeb(location,key==='android'?'apk':'asar');
const version=JSON.parse(await readFile('package.json','utf8')).version;
const report={version,commit:process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),builtAt:new Date().toISOString(),target:key,installer:target.file,format:target.format,architectures:target.architectures,...checked};
await writeFile('deliverables/BUILD_INFO.json',JSON.stringify(report,null,2)+'\n');
await writeFile(path.join('deliverables/release-current',`BUILD_INFO-${key}.json`),JSON.stringify(report,null,2)+'\n');
console.log(`PASS ${target.label}: ${checked.matchedWebFiles} web files and native bridge match the shared web build.`);
